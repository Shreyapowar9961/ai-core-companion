import uuid
from datetime import datetime, date
from sqlalchemy import Column, String, Integer, Float, Boolean, Date, DateTime, JSON, ForeignKey, Text
from sqlalchemy.orm import relationship
from app.core.database import Base

def gen_uuid():
    return str(uuid.uuid4())

class MonitoringPlan(Base):
    """
    Monitoring Plan configured by clinicians for post-discharge recovery.
    """
    __tablename__ = "monitoring_plans"

    id = Column(String(64), primary_key=True, default=gen_uuid)
    patient_id = Column(String(64), ForeignKey("patients.id"), nullable=False, index=True)
    clinician_id = Column(String(64), nullable=True)

    start_date = Column(Date, nullable=False, default=date.today)
    end_date = Column(Date, nullable=False)
    frequency = Column(String(32), default="DAILY") # DAILY, TWICE_DAILY, WEEKLY
    timezone = Column(String(64), default="Asia/Kolkata")
    approved_questions = Column(JSON, default=list) # List of approved question codes/labels
    communication_channel = Column(String(32), default="VOICE") # VOICE, WHATSAPP, SMS
    is_active = Column(Boolean, default=True)

    created_at = Column(DateTime, default=datetime.utcnow)
    updated_at = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)

    patient = relationship("Patient", backref="monitoring_plans")
    tasks = relationship("CheckinTask", back_populates="plan", cascade="all, delete-orphan")


class CheckinTask(Base):
    """
    Scheduled check-in task generated by the automated scheduler.
    """
    __tablename__ = "checkin_tasks"

    id = Column(String(64), primary_key=True, default=gen_uuid)
    monitoring_plan_id = Column(String(64), ForeignKey("monitoring_plans.id"), nullable=True, index=True)
    patient_id = Column(String(64), ForeignKey("patients.id"), nullable=False, index=True)

    scheduled_for = Column(DateTime, nullable=False, index=True)
    completed_at = Column(DateTime, nullable=True)
    status = Column(String(32), default="PENDING", index=True) # PENDING, COMPLETED, MISSED, EXPIRED
    channel = Column(String(32), default="VOICE") # VOICE, WHATSAPP, SMS, PORTAL

    response_json = Column(JSON, default=dict)
    # Categorisation: ROUTINE, FOLLOW_UP_REQUIRED, NEEDS_CLINICIAN_REVIEW, UNANSWERED
    category = Column(String(64), default="ROUTINE", index=True)
    category_reason = Column(Text, nullable=True)
    alert_id = Column(String(64), ForeignKey("alerts.id"), nullable=True)

    created_at = Column(DateTime, default=datetime.utcnow, index=True)

    plan = relationship("MonitoringPlan", back_populates="tasks")
    patient = relationship("Patient", backref="checkin_tasks")


class CommunicationLog(Base):
    """
    Communication log for all simulated channels (Simulated Voice, WhatsApp, SMS).
    Strictly ₹0 honest local simulation persisted in database.
    """
    __tablename__ = "communication_logs"

    id = Column(String(64), primary_key=True, default=gen_uuid)
    patient_id = Column(String(64), ForeignKey("patients.id"), nullable=False, index=True)

    # SIMULATED_VOICE, SIMULATED_WHATSAPP, SIMULATED_SMS
    channel = Column(String(32), nullable=False, index=True)
    # RECOVERY_CHECKIN, MEDICATION_REMINDER, FOLLOWUP_REMINDER, FEEDBACK_REQUEST
    message_type = Column(String(64), nullable=False, index=True)
    recipient_phone = Column(String(32), nullable=True)
    content = Column(Text, nullable=False)

    # GENERATED, SENT, DELIVERED, VIEWED, RESPONDED, FAILED
    status = Column(String(32), default="DELIVERED", index=True)
    is_simulated = Column(Boolean, default=True) # Honest indicator
    metadata_json = Column(JSON, default=dict)

    sent_at = Column(DateTime, default=datetime.utcnow, index=True)
    viewed_at = Column(DateTime, nullable=True)
    responded_at = Column(DateTime, nullable=True)

    patient = relationship("Patient", backref="communication_logs")


class PatientFeedback(Base):
    """
    Automated feedback submitted by patients after check-ins or follow-ups.
    """
    __tablename__ = "patient_feedbacks"

    id = Column(String(64), primary_key=True, default=gen_uuid)
    patient_id = Column(String(64), ForeignKey("patients.id"), nullable=False, index=True)
    checkin_task_id = Column(String(64), ForeignKey("checkin_tasks.id"), nullable=True)

    rating = Column(Integer, nullable=False) # 1 to 5
    category = Column(String(64), default="GENERAL_RECOVERY")
    comments = Column(Text, nullable=True)
    created_at = Column(DateTime, default=datetime.utcnow, index=True)

    patient = relationship("Patient", backref="feedbacks")
